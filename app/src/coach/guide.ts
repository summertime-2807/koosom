type N = Record<string, unknown>
const C = { bg: '#0f172a', card: '#1e293b', text: '#f1f5f9', sub: '#94a3b8', accent: '#34d399', btn: '#0ea5e9' }
const t = (s: string, o: N = {}): N => ({ type: 'text', text: s, color: C.text, size: 'sm', wrap: true, ...o })

interface Step {
  icon: string
  title: string
  when: string
  lines: string[]
  tip?: string
  buttons: [string, string][] // [ป้ายปุ่ม, ข้อความที่ส่ง]
}

function bubble(s: Step, i: number, total: number): N {
  return {
    type: 'bubble',
    size: 'kilo',
    styles: { header: { backgroundColor: C.card }, body: { backgroundColor: C.bg }, footer: { backgroundColor: C.bg } },
    header: {
      type: 'box',
      layout: 'vertical',
      paddingAll: '14px',
      contents: [t(`ขั้นที่ ${i + 1}/${total} · ${s.when}`, { size: 'xxs', color: C.accent }), t(`${s.icon} ${s.title}`, { size: 'lg', weight: 'bold', margin: 'xs' })],
    },
    body: {
      type: 'box',
      layout: 'vertical',
      paddingAll: '14px',
      spacing: 'sm',
      contents: [
        ...s.lines.map((l) => t(l, { size: 'sm' })),
        ...(s.tip ? [{ type: 'separator', color: '#334155', margin: 'md' }, t(`💡 ${s.tip}`, { size: 'xs', color: C.sub, margin: 'md' })] : []),
      ],
    },
    footer: {
      type: 'box',
      layout: 'vertical',
      spacing: 'sm',
      paddingAll: '12px',
      contents: s.buttons.map(([label, text]) => ({ type: 'button', style: 'primary', height: 'sm', color: C.btn, action: { type: 'message', label, text } })),
    },
  }
}

