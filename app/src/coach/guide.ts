export function guideMessages(sport: Sport): LineMessage[] {
  const steps = sport === 'badminton' ? BADMINTON : RUN
  return [
    flex(
      sport === 'badminton' ? '📖 วิธีใช้คู่ซ้อม (แบดมินตัน)' : '📖 วิธีใช้คู่ซ้อม (วิ่ง)',
      { type: 'carousel', contents: steps.map((s, i) => bubble(s, i, steps.length)) },
    ),
  ]
}

